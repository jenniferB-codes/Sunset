CREATE DATABASE IF NOT EXISTS willow_linen CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE willow_linen;
CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS bookings (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  product_name VARCHAR(100) NOT NULL,
  product_price DECIMAL(10,2) NOT NULL,
  activity_name VARCHAR(100) NOT NULL,
  activity_price DECIMAL(10,2) NOT NULL,
  people TINYINT UNSIGNED NOT NULL,
  event_date DATE NOT NULL,
  comments VARCHAR(500) NOT NULL DEFAULT '',
  total DECIMAL(10,2) NOT NULL,
  extras_summary VARCHAR(500) NOT NULL DEFAULT 'Ninguno',
  extras_total DECIMAL(10,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
